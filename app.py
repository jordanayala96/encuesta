def setting(key, default=""):
    try:
        return str(st.secrets[key])
    except (KeyError, FileNotFoundError):
        return os.environ.get(key, default)

def db_connection():
    url = setting("DATABASE_URL")
    if not url:
        raise RuntimeError("Falta DATABASE_URL en los secretos de Streamlit.")
    return psycopg.connect(url, connect_timeout=10, sslmode="require")


def inicializar_db(con):
    con.execute("""CREATE TABLE IF NOT EXISTS respuestas (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        creado_utc TEXT NOT NULL,
        zona TEXT NOT NULL,
        formulario TEXT NOT NULL,
        fase TEXT NOT NULL,
        actividad TEXT NOT NULL,
        calificacion INTEGER,
        recomendacion TEXT NOT NULL,
        envio_id TEXT
    )""")
    con.execute("ALTER TABLE respuestas ADD COLUMN IF NOT EXISTS envio_id TEXT")


def guardar(zona, formulario, respuestas):
    envio_id = uuid.uuid4().hex
    creado_utc = datetime.now(timezone.utc).isoformat()
    filas = [
        (creado_utc, zona, formulario, fase, actividad, calificacion, recomendacion, envio_id)
        for fase, actividad, calificacion, recomendacion in respuestas
    ]
    # La transacción se confirma al salir; si falla una fila se revierten todas.
    with db_connection() as con:
        inicializar_db(con)
        with con.cursor() as cur:
            cur.executemany("""INSERT INTO respuestas
                (creado_utc,zona,formulario,fase,actividad,calificacion,recomendacion,envio_id)
                VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""", filas)


def datos():
    with db_connection() as con:
        inicializar_db(con)
        with con.cursor() as cur:
            cur.execute("SELECT * FROM respuestas ORDER BY id DESC")
            return pd.DataFrame(cur.fetchall(), columns=[col.name for col in cur.description])


def exportar_csv_seguro(df):
    copia = df.copy()
    for columna in copia.select_dtypes(include=["object", "string"]).columns:
        copia[columna] = copia[columna].map(
            lambda valor: "'" + valor if isinstance(valor, str) and valor.lstrip().startswith(("=", "+", "-", "@")) else valor
        )
    return copia.to_csv(index=False).encode("utf-8-sig")


def guardar_excel_como_texto(hoja):
    # openpyxl interpreta cadenas que comienzan con '=' como fórmulas.
    for fila in hoja:
        for celda in fila:
            if celda.data_type == "f":
                celda.data_type = "s"


def autenticar(usuario, clave):
    correcto_usuario = setting("ADMIN_USER")
    clave_configurada = setting("ADMIN_PASSWORD")
    if not correcto_usuario or not clave_configurada:
        return False
    return hmac.compare_digest(usuario, correcto_usuario) and hmac.compare_digest(clave, clave_configurada)

